#!/usr/bin/env node
// data/cities/*.json -> wechat-manual/utils/cities.js (CommonJS, full field set for manual browsing)
// 用法: node scripts/build-manual.mjs  (与 build-data.mjs 同数据源)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CITIES_DIR = join(ROOT, 'data', 'cities');
const OUT = join(ROOT, 'wechat-manual', 'utils', 'cities.js');

// 维度定义 (与 build-data.mjs 同顺序) + 每维度字段中文名映射
const DIMS = [
  ['economy_opportunity', '经济机会', {
    avg_salary_yearly: '省平均工资', job_density_index: '岗位密度指数',
    key_industries: '重点产业', unemployment_rate: '失业率',
  }],
  ['housing_difficulty', '买房难度', {
    avg_price_per_sqm: '平均房价', price_to_income_ratio: '房价收入比',
    downpayment_median: '首付中位数', purchase_restrictions: '限购政策',
    mortgage_rate_first: '首套房贷利率',
  }],
  ['hukou_policy', '落户政策', {
    hukou_difficulty_score: '落户难度评分', hukou_policy_summary: '落户政策摘要',
    social_security_years_required: '社保年限要求',
  }],
  ['social_insurance', '五险一金', {
    housing_fund_rate: '公积金缴存比例', housing_fund_cap_loan: '公积金贷款上限',
    pension_base_lower: '养老缴费基数下限', pension_base_upper: '养老缴费基数上限',
    medical_reimbursement_inpatient: '住院医保报销', maternity_leave_days: '产假天数',
    unemployment_benefit_monthly: '失业金标准', work_injury_base: '工伤缴费基数',
  }],
  ['livability', '宜居条件', {
    avg_commute_minutes: '平均通勤时长', tier3_hospitals: '三甲医院数量',
    aqi_good_days_ratio: '空气优良天数比例', climate_summary: '气候特点',
    cultural_facilities_index: '文化设施指数', education_resources: '教育资源',
  }],
  ['talent_policy', '人才政策', {
    fresh_grad_subsidy: '应届毕业生补贴', high_level_talent_policy: '高层次人才政策',
    rent_subsidy: '租房补贴', settlement_allowance: '安家费',
  }],
];

const SRC_TITLE = '2024年国民经济和社会发展统计公报';

function shortUnit(u) {
  if (!u) return '';
  const s = String(u);
  if (s.length <= 40) return s;
  const i = s.indexOf('；');
  return i > 0 && i <= 45 ? s.slice(0, i) : s.slice(0, 40) + '…';
}

function fmtValue(v) {
  if (v == null) return null;
  if (Array.isArray(v)) return v.join('、');
  if (typeof v === 'number') return Number.isInteger(v) ? v : Math.round(v * 100) / 100;
  return String(v);
}

const files = readdirSync(CITIES_DIR).filter(f => f.endsWith('.json') && !f.startsWith('_')).sort();
const cities = [];
for (const file of files) {
  const raw = JSON.parse(readFileSync(join(CITIES_DIR, file), 'utf8'));
  const dimRaw = raw.dimensions || {};
  const dims = [];
  for (const [dkey, dname, fieldMap] of DIMS) {
    const sec = dimRaw[dkey] || {};
    const fields = [];
    for (const [fkey, label] of Object.entries(fieldMap)) {
      const f = sec[fkey];
      if (!f) {
        fields.push({ key: fkey, label, value: null, unit: '', src: null });
        continue;
      }
      const url = f.source && f.source.url && !String(f.source.url).startsWith('N/A')
        ? String(f.source.url) : null;
      fields.push({ key: fkey, label, value: fmtValue(f.value), unit: shortUnit(f.unit), src: url });
    }
    dims.push({ key: dkey, name: dname, fields });
  }
  cities.push({ name: raw.city, pinyin: raw.city_pinyin, tier: raw.tier, dims });
}

const banner = `// AUTO-GENERATED by scripts/build-manual.mjs — DO NOT EDIT. Run: node scripts/build-manual.mjs\n`;
const body = banner + `const CITIES = ${JSON.stringify(cities)};\nconst SRC_TITLE = ${JSON.stringify(SRC_TITLE)};\nmodule.exports = { CITIES, SRC_TITLE };\n`;
writeFileSync(OUT, body);
console.log(`wechat-manual/utils/cities.js: ${cities.length} 城, ${Math.round(body.length / 1024)} KB`);
